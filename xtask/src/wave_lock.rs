    /// The lock text from `[[emptied]]` to the section after it — the proof-block slice.
    fn emptied_slice(text: &str) -> &str {
        let start = text.find("[[emptied]]").expect("emptied section present");
        let end = text[start..]
            .find("\n[owns]")
            .map(|i| start + i)
            .unwrap_or(text.len());
        &text[start..end]
    }

